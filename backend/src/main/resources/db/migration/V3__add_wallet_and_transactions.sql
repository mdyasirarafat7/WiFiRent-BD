-- V3__add_wallet_and_transactions.sql
-- Internal demo wallet system (virtual credits only, no real money)

CREATE TABLE wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    user_id BIGINT NOT NULL UNIQUE,
    balance_minor_units BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wallet_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT chk_wallet_balance_non_negative CHECK (balance_minor_units >= 0)
);

CREATE INDEX idx_wallet_user ON wallets(user_id);

CREATE TABLE wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    wallet_id BIGINT NOT NULL,
    transaction_type VARCHAR(30) NOT NULL,
    amount_minor_units BIGINT NOT NULL,
    reference_id VARCHAR(255) NOT NULL,
    reference_type VARCHAR(50) NOT NULL,
    description VARCHAR(1000),
    idempotency_key VARCHAR(255) UNIQUE,
    CONSTRAINT fk_wallet_transaction_wallet FOREIGN KEY (wallet_id) REFERENCES wallets(id),
    CONSTRAINT chk_wallet_transaction_amount_nonzero CHECK (amount_minor_units <> 0)
);

CREATE INDEX idx_wallet_transaction_wallet ON wallet_transactions(wallet_id);
CREATE INDEX idx_wallet_transaction_idempotency ON wallet_transactions(idempotency_key);
CREATE INDEX idx_wallet_transaction_reference ON wallet_transactions(reference_type, reference_id);
