-- V1__initial_schema.sql
-- WiFiRent BD initial schema

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    is_email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    phone VARCHAR(30)
);

CREATE TABLE host_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    user_id BIGINT NOT NULL UNIQUE,
    business_name VARCHAR(200),
    address VARCHAR(500),
    is_approved BOOLEAN NOT NULL DEFAULT FALSE,
    commission_rate_bps INTEGER NOT NULL DEFAULT 100,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT fk_host_profile_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE hotspots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    latitude NUMERIC(10,6) NOT NULL,
    longitude NUMERIC(11,6) NOT NULL,
    ssid VARCHAR(100),
    approximate_area VARCHAR(100),
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    host_id BIGINT NOT NULL,
    CONSTRAINT fk_hotspot_host FOREIGN KEY (host_id) REFERENCES host_profiles(id)
);

CREATE INDEX idx_hotspot_host ON hotspots(host_id);
CREATE INDEX idx_hotspot_location ON hotspots(latitude, longitude);

CREATE TABLE gateway_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    device_id VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    management_url VARCHAR(500),
    adapter_type VARCHAR(255) NOT NULL DEFAULT 'MOCK',
    is_online BOOLEAN NOT NULL DEFAULT FALSE,
    last_heartbeat_at TIMESTAMP WITHOUT TIME ZONE,
    status VARCHAR(20) NOT NULL DEFAULT 'OFFLINE',
    hotspot_id BIGINT NOT NULL,
    shared_secret VARCHAR(500),
    CONSTRAINT fk_gateway_hotspot FOREIGN KEY (hotspot_id) REFERENCES hotspots(id)
);

CREATE TABLE package_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    price_minor_units BIGINT NOT NULL DEFAULT 0,
    package_type VARCHAR(20) NOT NULL,
    duration_minutes INTEGER,
    data_quota_bytes BIGINT,
    validity_minutes INTEGER,
    speed_limit_kbps INTEGER,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    hotspot_id BIGINT NOT NULL,
    CONSTRAINT fk_package_hotspot FOREIGN KEY (hotspot_id) REFERENCES hotspots(id)
);

CREATE INDEX idx_package_hotspot ON package_plans(hotspot_id);

CREATE TABLE rental_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    customer_id BIGINT NOT NULL,
    hotspot_id BIGINT NOT NULL,
    package_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    total_price_minor_units BIGINT NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(255) UNIQUE,
    cancelled_at TIMESTAMP WITHOUT TIME ZONE,
    cancellation_reason VARCHAR(500),
    CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES users(id),
    CONSTRAINT fk_order_hotspot FOREIGN KEY (hotspot_id) REFERENCES hotspots(id),
    CONSTRAINT fk_order_package FOREIGN KEY (package_id) REFERENCES package_plans(id)
);

CREATE INDEX idx_order_customer ON rental_orders(customer_id);
CREATE INDEX idx_order_hotspot ON rental_orders(hotspot_id);
CREATE INDEX idx_order_idempotency ON rental_orders(idempotency_key);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    rental_order_id BIGINT NOT NULL,
    provider VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    provider_transaction_ref VARCHAR(255) NOT NULL,
    amount_minor_units BIGINT NOT NULL DEFAULT 0,
    currency VARCHAR(10) NOT NULL DEFAULT 'BDT',
    idempotency_key VARCHAR(255),
    callback_received_at TIMESTAMP WITHOUT TIME ZONE,
    callback_payload VARCHAR(1000),
    failure_reason VARCHAR(500),
    CONSTRAINT fk_payment_order FOREIGN KEY (rental_order_id) REFERENCES rental_orders(id)
);

CREATE INDEX idx_payment_order ON payments(rental_order_id);
CREATE INDEX idx_payment_ref ON payments(provider_transaction_ref);

CREATE TABLE rental_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    customer_id BIGINT NOT NULL,
    hotspot_id BIGINT NOT NULL,
    package_id BIGINT NOT NULL,
    rental_order_id BIGINT NOT NULL,
    started_at TIMESTAMP WITHOUT TIME ZONE,
    expires_at TIMESTAMP WITHOUT TIME ZONE,
    data_quota_bytes BIGINT,
    consumed_bytes BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    gateway_session_id VARCHAR(255),
    gateway_device_id VARCHAR(100),
    CONSTRAINT fk_session_customer FOREIGN KEY (customer_id) REFERENCES users(id),
    CONSTRAINT fk_session_hotspot FOREIGN KEY (hotspot_id) REFERENCES hotspots(id),
    CONSTRAINT fk_session_package FOREIGN KEY (package_id) REFERENCES package_plans(id),
    CONSTRAINT fk_session_order FOREIGN KEY (rental_order_id) REFERENCES rental_orders(id)
);

CREATE INDEX idx_session_customer ON rental_sessions(customer_id);
CREATE INDEX idx_session_status ON rental_sessions(status);
CREATE INDEX idx_session_expires ON rental_sessions(expires_at);
CREATE INDEX idx_session_gateway ON rental_sessions(gateway_session_id);

CREATE TABLE usage_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    session_id VARCHAR(255) NOT NULL,
    recorded_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    consumed_bytes BIGINT NOT NULL DEFAULT 0,
    duration_seconds BIGINT NOT NULL DEFAULT 0,
    source VARCHAR(50) NOT NULL DEFAULT 'gateway'
);

CREATE INDEX idx_usage_session ON usage_records(session_id);

CREATE TABLE host_ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    host_id BIGINT NOT NULL,
    entry_type VARCHAR(30) NOT NULL,
    amount_minor_units BIGINT NOT NULL DEFAULT 0,
    currency VARCHAR(10) NOT NULL DEFAULT 'BDT',
    reference_id VARCHAR(255),
    reference_type VARCHAR(50),
    description VARCHAR(500),
    CONSTRAINT fk_ledger_host FOREIGN KEY (host_id) REFERENCES users(id)
);

CREATE INDEX idx_ledger_host ON host_ledger_entries(host_id);

CREATE TABLE refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    payment_id BIGINT NOT NULL,
    rental_order_id BIGINT NOT NULL,
    amount_minor_units BIGINT NOT NULL DEFAULT 0,
    currency VARCHAR(10) NOT NULL DEFAULT 'BDT',
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    requested_by_admin_id BIGINT,
    processed_at TIMESTAMP WITHOUT TIME ZONE,
    reason VARCHAR(500),
    CONSTRAINT fk_refund_payment FOREIGN KEY (payment_id) REFERENCES payments(id),
    CONSTRAINT fk_refund_order FOREIGN KEY (rental_order_id) REFERENCES rental_orders(id)
);

CREATE INDEX idx_refund_payment ON refunds(payment_id);
CREATE INDEX idx_refund_order ON refunds(rental_order_id);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    actor_user_id BIGINT,
    actor_role VARCHAR(20),
    action VARCHAR(30) NOT NULL,
    entity_type VARCHAR(50),
    entity_id VARCHAR(100),
    details VARCHAR(1000),
    ip_address VARCHAR(45)
);

CREATE INDEX idx_audit_created ON audit_logs(created_at);
